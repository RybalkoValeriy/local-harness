// Optional browser check; uses a disposable folder in the legacy workspace.
const { chromium } = require("../tmp/browser-probe/node_modules/playwright")
const assert = require("node:assert/strict")
const fs = require("node:fs/promises")
const path = require("node:path")

;(async () => {
  const fixture = await fs.mkdtemp(path.resolve("workspace/tree-browser-check-"))
  const folder = path.basename(fixture)
  await fs.mkdir(path.join(fixture, "empty"))
  await fs.writeFile(path.join(fixture, "before.rb"), 'class Greeter\n  def call\n    "Hello"\n  end\nend\n')
  await fs.writeFile(path.join(fixture, "second.ts"), 'const message: string = "Hello"\n')
  const browser = await chromium.launch({ channel: "chrome", headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  page.on("console", message => { if (message.type() === "error") console.error(message.text()) })
  try {
    await page.goto("http://localhost:3000/projects/1", { waitUntil: "networkidle" })
    await page.getByText(folder, { exact: true }).click()
    const files = page.getByRole("navigation", { name: "Project files" })
    await files.getByText("before.rb", { exact: true }).waitFor()
    await files.getByRole("button", { name: "before.rb", exact: true }).click()
    const viewer = page.getByRole("tabpanel")
    await viewer.locator(".hljs-keyword").first().waitFor()
    assert.match(await viewer.locator("code").innerText(), /class Greeter/)
    await fs.writeFile(path.join(fixture, "before.rb"), 'class UpdatedGreeter\nend\n# <script>window.injected = true</script>\n')
    await page.waitForFunction(() => document.querySelector(".editor-document code")?.textContent.includes("UpdatedGreeter"))
    assert.equal(await page.evaluate(() => window.injected), undefined)
    await page.screenshot({ path: path.resolve("tmp/file-viewer-desktop.png"), fullPage: true })
    await files.getByRole("button", { name: "second.ts", exact: true }).click()
    await page.waitForFunction(() => document.querySelector(".editor-document code")?.textContent.includes("const message"))
    assert.equal(await page.getByRole("tab").count(), 2)
    await page.getByRole("tab", { name: "before.rb", exact: true }).click()
    await viewer.locator(".hljs-keyword").first().waitFor()
    assert.equal(await page.getByRole("tab").count(), 2)
    assert.match(await viewer.locator("code").innerText(), /UpdatedGreeter/)
    await page.getByRole("tab", { name: "before.rb", exact: true }).focus()
    await page.keyboard.press("ArrowRight")
    assert.equal(await page.getByRole("tab", { name: "second.ts", exact: true }).getAttribute("aria-selected"), "true")
    await page.keyboard.press("ArrowLeft")
    assert.equal(await page.getByRole("tab", { name: "before.rb", exact: true }).getAttribute("aria-selected"), "true")
    await page.getByRole("button", { name: `Close ${folder}/second.ts`, exact: true }).click()
    assert.equal(await page.getByRole("tab").count(), 1)
    assert.equal(await page.locator("dialog").count(), 0)
    await files.getByText("empty", { exact: true }).click()
    await files.getByText("Empty folder", { exact: true }).waitFor()
    await page.route("**/conversations/*/run", async route => {
      await fs.writeFile(path.join(fixture, "after.rb"), "puts :after\n")
      const events = [
        { type: "step", number: 37 },
        { type: "tool", name: "create_file", arguments: "{}", result: JSON.stringify({ path: `${folder}/after.rb`, action: "created" }) },
        { type: "done" }
      ]
      await route.fulfill({ status: 200, contentType: "application/x-ndjson", body: events.map(event => JSON.stringify(event)).join("\n") + "\n" })
    })
    await page.locator("#prompt").fill("Browser fixture: create a file")
    await page.getByRole("button", { name: "Send message" }).click()
    await files.getByText("after.rb", { exact: true }).waitFor()
    assert.match(await page.locator(".workspace-strip").innerText(), /No step limit/)
    await fs.writeFile(path.join(fixture, "external.txt"), "outside app")
    await page.getByRole("button", { name: "Refresh files" }).click()
    await files.getByText("external.txt", { exact: true }).waitFor()
    await fs.writeFile(path.join(fixture, "polled.txt"), "Detected without a manual refresh")
    await files.getByRole("button", { name: "polled.txt", exact: true }).waitFor()
    await page.screenshot({ path: path.resolve("tmp/file-tree-desktop.png"), fullPage: true })
    await page.getByLabel("Theme", { exact: true }).selectOption("dark")
    await page.screenshot({ path: path.resolve("tmp/file-editor-dark.png"), fullPage: true })
    await page.setViewportSize({ width: 1100, height: 900 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.screenshot({ path: path.resolve("tmp/file-tree-mobile.png"), fullPage: true })
    await files.getByRole("button", { name: "before.rb", exact: true }).click()
    await viewer.locator(".hljs-keyword").first().waitFor()
    await page.screenshot({ path: path.resolve("tmp/file-viewer-mobile.png"), fullPage: true })
    await fs.unlink(path.join(fixture, "before.rb"))
    await page.waitForFunction(() => document.querySelector(".editor-document code")?.textContent === "")
    assert.match(await viewer.locator(".file-viewer-status").innerText(), /No such file|unavailable|ordinary text/)
    await page.getByRole("button", { name: `Close ${folder}/before.rb`, exact: true }).click()
    assert.equal(await page.locator(".editor-empty").isVisible(), true)
    await page.locator(".project-files > details > summary").click()
    assert.equal(await files.isVisible(), false)
    assert.deepEqual(errors, [])
    console.log("PASS: persistent editor tabs, switching/closing without duplicates, highlighting, live disk sync, deleted-file errors, escaped HTML, chat interaction, desktop/mobile, no JS errors.")
  } finally {
    if (errors.length) console.error(errors)
    await browser.close()
    assert.equal(path.dirname(path.resolve(fixture)), path.resolve("workspace"))
    assert(path.basename(fixture).startsWith("tree-browser-check-"))
    await fs.rm(fixture, { recursive: true, force: true })
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
