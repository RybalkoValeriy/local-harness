// Requires the optional Playwright installation documented in browser-smoke.cjs.
const { chromium } = require("../tmp/browser-probe/node_modules/playwright")
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")

;(async () => {
  const fixture = fs.mkdtempSync(path.resolve("tmp/browser-project-check-"))
  fs.writeFileSync(path.join(fixture, "README.md"), "Browser project check fixture")
  const paths = []
  const browser = await chromium.launch({ channel: "chrome", headless: true })
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, colorScheme: "light" })
  const page = await context.newPage()
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  try {
    await page.goto("http://localhost:3000", { waitUntil: "networkidle" })
    await page.getByLabel("Theme", { exact: true }).selectOption("dark")
    assert.equal(await page.locator("html").getAttribute("data-theme"), "dark")
    await page.reload({ waitUntil: "networkidle" })
    assert.equal(await page.getByLabel("Theme", { exact: true }).inputValue(), "dark")
    assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), "rgb(16, 22, 19)")
    const existing = page.locator(".project-form").filter({ has: page.getByRole("heading", { name: "Open existing folder" }) })
    await existing.getByRole("button", { name: "Browse folders…" }).click()
    let dialog = page.getByRole("dialog", { name: "Choose folder" })
    await dialog.getByRole("button", { name: "Select this folder" }).waitFor()
    await dialog.getByLabel("Browse folder path").fill('"' + fixture + '"')
    await dialog.getByRole("button", { name: "Go", exact: true }).click()
    await page.waitForFunction(() => document.querySelector("dialog[open] [data-folder-picker-target=current]").textContent.includes("browser-project-check-"))
    await page.screenshot({ path: path.resolve("tmp/folder-picker-dark.png"), fullPage: true })
    await dialog.getByRole("button", { name: "Select this folder" }).click()
    const canonical = await existing.getByLabel("Absolute folder path").inputValue()
    assert.match(canonical, /^\/mnt\/c\/.*browser-project-check-/)
    paths.push(canonical)
    await existing.getByLabel("Project name").fill("Browser project check")
    await existing.getByRole("button", { name: "Open folder", exact: true }).click()
    await page.waitForURL(/\/projects\/\d+$/)
    assert.match(await page.locator(".workspace-strip").innerText(), /Browser project check/)
    await page.getByRole("link", { name: "ALL PROJECTS", exact: true }).click()
    const create = page.locator(".project-form").filter({ has: page.getByRole("heading", { name: "Create project", exact: true }) })
    await create.getByRole("button", { name: "Browse folders…" }).click()
    dialog = page.getByRole("dialog", { name: "Choose folder" })
    await dialog.getByLabel("Browse folder path").fill(canonical)
    await dialog.getByRole("button", { name: "Go", exact: true }).click()
    await page.waitForFunction(expected => document.querySelector("dialog[open] [data-folder-picker-target=current]").textContent === expected, canonical)
    await dialog.getByRole("button", { name: "Select this folder" }).click()
    await create.getByLabel("Project name").fill("Browser child check")
    await create.getByLabel("New folder name").fill("child")
    await create.getByRole("button", { name: "Create project", exact: true }).click()
    await page.waitForURL(/\/projects\/\d+$/)
    assert(fs.statSync(path.join(fixture, "child")).isDirectory())
    paths.push(canonical + "/child")
    await page.getByRole("link", { name: "ALL PROJECTS", exact: true }).click()
    await page.getByLabel("Theme", { exact: true }).selectOption("light")
    assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), "rgb(250, 251, 249)")
    await page.screenshot({ path: path.resolve("tmp/projects-theme-light.png"), fullPage: true })
    await page.getByLabel("Theme", { exact: true }).selectOption("system")
    await page.emulateMedia({ colorScheme: "dark" })
    await page.waitForFunction(() => document.documentElement.dataset.theme === "dark")
    await page.emulateMedia({ colorScheme: "light" })
    await page.waitForFunction(() => document.documentElement.dataset.theme === "light")
    await page.setViewportSize({ width: 390, height: 844 })
    await existing.getByRole("button", { name: "Browse folders…" }).click()
    await page.getByRole("dialog").waitFor()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.screenshot({ path: path.resolve("tmp/folder-picker-mobile.png"), fullPage: true })
    assert.deepEqual(errors, [])
    console.log("Passed: browse/register existing Windows folder, browse/create child project, dark/light/system, persistence, mobile layout")
  } finally {
    fs.writeFileSync("tmp/browser-projects-result.json", JSON.stringify({ paths, fixture }))
    await browser.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
